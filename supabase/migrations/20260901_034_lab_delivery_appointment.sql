-- MOD-FEAT-034 | نوبت تحویل کار لابراتوار
-- اعمال‌شده روی دیتابیس زنده در ۱۴۰۵/۰۶/۱۱، پیش از انتشار کد.
--
-- کلینیک و لابراتوار دو زنجیره‌ی متفاوت دارند و برنامه زنجیره‌ی لابراتوار
-- را نشان می‌داد:
--
--   کلینیک:   ارسال → موعد رسیدن → رسید → نوبت بیمار → تحویل
--   لابراتوار: قالب‌گیری → پیک → CAD/CAM → پخت → کنترل کیفی → آماده
--
-- هر چیزی در فهرست دوم داخل ساختمان لابراتوار اتفاق می‌افتد. مطب نه
-- می‌تواند ببیندش، نه رویش کاری کند، و نه لازمش دارد.
--
-- از زنجیره‌ی مطب چهار حلقه ستون داشتند: sent_at، deadline، received_at،
-- delivered. حلقه‌ی گم‌شده نوبتی است که برای تحویل کار به بیمار گذاشته
-- می‌شود — همان گامی که حلقه را می‌بندد و بیشتر از همه فراموش می‌شود.
--
-- Nullable و بدون محدودیت ترتیب: کار اغلب پیش از آنکه کسی نوبت بگذارد
-- می‌رسد، و اجبار ترتیب در schema یعنی ثبت واقعیت غیرممکن شود.

alter table lab_orders
  add column if not exists delivery_appointment_id uuid references appointments(id);

create index if not exists idx_lab_orders_delivery_appointment
  on lab_orders(delivery_appointment_id);

comment on column lab_orders.delivery_appointment_id is
  'نوبتی که برای تحویل کار به بیمار گذاشته شده — حلقه‌ی آخر زنجیره‌ی مطب';
